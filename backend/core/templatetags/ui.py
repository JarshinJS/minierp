@register.filter
def mul(value, arg):
    """Multiply two numbers (Decimal-safe), e.g. {{ line.quantity|mul:line.unit_cost }}."""
    from decimal import Decimal, InvalidOperation
    try:
        return Decimal(str(value)) * Decimal(str(arg))
    except (InvalidOperation, TypeError, ValueError):
        return ""


@register.filter
def has_role(user, roles):
    """Mirror RoleRequiredMixin in templates: {% if request.user|has_role:"ADMIN,TRADE_MANAGER" %}.
    ADMIN always passes, exactly like the view mixin."""
    role = getattr(user, "role", None)
    if not role:
        return False
    return role == "ADMIN" or role in [r.strip() for r in str(roles).split(",")]
