@register.filter
def status_tone(value):
    return _TONE_LOOKUP.get(str(value or "").upper(), "gray")


@register.simple_tag
def status_badge(value, label=None):
    tone = status_tone(value)
    text = label or str(value or "").replace("_", " ").title()
    return format_html('<span class="badge badge-{}">{}</span>', tone, text)


@register.filter
def initials(value):
    parts = [p for p in str(value or "").split() if p]
    if not parts:
        return "?"
    if len(parts) == 1:
        return parts[0][:2].upper()
    return (parts[0][0] + parts[-1][0]).upper()


@register.filter
def parse_iso(value):
    """Turn an ISO-8601 string (as produced by serializers) into a datetime for |date / |timesince."""
    from django.utils.dateparse import parse_datetime
    if not value or not isinstance(value, str):
        return value
    return parse_datetime(value) or value


